import { chooseOption } from './studio-select.mjs'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
import { settingImage } from '../shared/outfits.mjs'

/** 经真实桌面核对单镜、批量、独立素材的声明和修复，最后留下已配图的待生成分镜。 */
export async function verifyVideoAssetReview(page, testRoot) {
  const editor = page.getByLabel('画面与运镜', { exact: false })
  const batch = page.getByRole('dialog', { name: '批量生成分镜视频' })
  const button = (name) => page.getByRole('button', { name, exact: true })
  await editor.fill('青色光带逐渐淡出')
  await button('生成分镜视频').click()
  const generation = page.getByRole('dialog', { name: '生成素材' })
  const start = generation.getByRole('button', { name: '开始生成' })
  await generation.getByLabel('此镜头无需出场资产').waitFor()
  assert.equal(await start.isDisabled(), true)
  await generation.getByLabel('此镜头无需出场资产').check()
  await start.waitFor()
  assert.equal(await start.isEnabled(), true)
  await generation.getByRole('button', { name: '关闭' }).click()
  await editor.fill('叶宁走进雨中。')
  await button('引用此资产').click()
  assert.equal(await editor.locator('[data-card-id]').count(), 1)
  assert.equal(await page.getByLabel('此镜头无需出场资产').count(), 0)
  await button('生成缺失视频').click()
  assert.equal(await batch.getByRole('checkbox').isDisabled(), true)
  assert.match(await batch.innerText(), /叶宁.*缺少参考图/)
  await batch.getByRole('button', { name: '核对分镜' }).click()
  await button('生成分镜视频').click()
  assert.equal(await start.isDisabled(), true)
  await chooseOption(page, generation.getByLabel('为叶宁 · 旅行风衣绑定参考图'), 0)
  assert.equal(await start.isEnabled(), true)
  await generation.getByRole('button', { name: '关闭' }).click()
  await button('素材库').click()
  await button('生成素材').click()
  await chooseOption(page, generation.getByLabel('视频归属'), 'library')
  const standalone = generation.getByRole('textbox', { name: '视频画面与运镜' })
  await standalone.fill('光点淡出。')
  assert.equal(await start.isDisabled(), true)
  await generation.getByLabel('此镜头无需出场资产').check()
  assert.equal(await start.isEnabled(), true)
  await standalone.fill('叶宁经过街角。')
  assert.equal(await start.isDisabled(), true)
  await generation.getByRole('button', { name: '引用此资产' }).click()
  assert.equal(await standalone.locator('[data-card-id]').count(), 1)
  assert.equal(await start.isEnabled(), true)
  await standalone.focus()
  await standalone.press('End')
  await page.keyboard.insertText('举起@星灯')
  await page.getByRole('button', { name: '新建设定卡', exact: true }).click()
  assert.equal(await generation.getByLabel('设定名称').inputValue(), '星灯')
  await chooseOption(page, generation.getByLabel('设定类型'), '道具')
  await generation.getByRole('button', { name: '新建并引用' }).click()
  assert.equal(await standalone.locator('[data-card-id]').count(), 2)
  assert.equal(await start.isDisabled(), true)
  await generation.getByRole('button', { name: '为星灯导入参考图' }).click()
  await generation.getByText('2 / 2 项已配图').waitFor()
  assert.equal(await start.isEnabled(), true)
  await generation.getByRole('button', { name: '关闭' }).click()
  await button('命令工作台').click()
  const command = page.getByRole('dialog', { name: '命令工作台' })
  const execute = command.getByRole('button', { name: '运行命令' })
  await chooseOption(page, command.getByLabel('临时服务环境'), 'aliyun-video')
  assert.equal(await execute.isDisabled(), true)
  await chooseOption(page, command.getByLabel('接收 STUDIO_OUTPUT'), '.mp4')
  await command.getByRole('textbox', { name: '视频画面与运镜' }).fill('光点淡出。')
  assert.equal(await execute.isDisabled(), true)
  await command.getByLabel('此镜头无需出场资产').check()
  assert.equal(await execute.isEnabled(), true)
  await command.getByRole('button', { name: '关闭' }).click()
  await button('分镜工作台').click()
  assert.match(await page.getByRole('region', { name: '出场资产核对' }).innerText(), /1 \/ 1 项已配图/)
  await verifyOfflineImage(page, testRoot)
}

/** 在临时工程移走一张已绑定的图，再从素材库恢复，检查两个出场引用和首帧状态。 */
async function verifyOfflineImage(page, testRoot) {
  const current = await page.evaluate(async () => (await window.studio.initial()).current)
  // 移动素材前确认工程直属于测试目录，按当前平台的路径规则比较。
  const root = await fs.realpath(current.root)
  assert.equal(path.relative(await fs.realpath(testRoot), path.dirname(root)), '')
  const card = current.data.cards.find((item) => item.name === '叶宁')
  const item = current.data.assets.find((asset) => asset.id === settingImage(card))
  assert.equal(item.id, current.data.episodes[0].shots[0].referenceId)
  const button = (name) => page.getByRole('button', { name, exact: true })
  const review = page.getByRole('region', { name: '出场资产核对' })
  await button('项目工作台').click()
  await fs.rename(path.join(root, 'media', item.id + item.ext), path.join(testRoot, '移出的参考图.png'))
  await page.locator('.home-projects button').filter({ hasText: current.root }).click()
  await button('分镜工作台').click()
  await review.getByText(/角色「叶宁 · 旅行风衣」的参考图文件已丢失或损坏/).waitFor()
  await review.getByText(/分镜「新镜头」的参考图文件已丢失或损坏/).waitFor()
  await button('生成缺失视频').click()
  const batch = page.getByRole('dialog', { name: '批量生成分镜视频' })
  assert.equal(await batch.getByRole('checkbox').isDisabled(), true)
  await batch.getByRole('button', { name: '关闭批量生成' }).click()
  await button('素材库').click()
  await page
    .locator('button.pool-item')
    .filter({ has: page.locator('img[src$="' + item.id + '"]') })
    .click()
  await button('找回丢失的原图').click()
  await page.getByText('原图已恢复，关联分镜可继续使用').waitFor()
  await button('分镜工作台').click()
  await review.getByText('1 / 1 项已配图').waitFor()
}
